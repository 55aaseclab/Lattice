import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const HYPERFRAMES_HOST_SCHEMA = "lattice.hyperframes-host.v1";
export const HYPERFRAMES_COMPOSITION_ID = "root";
export const HOST_PUBLIC_MANIFEST_NAME = "lattice-host-manifest.json";
export const HOST_COMPOSITION_DIRNAME = "composition";
export const HOST_ENTRY_NAME = "index.html";
export const HOST_BUNDLE_DIRNAME = "bundle";

const DO_NOT_EDIT = "DO NOT EDIT — generated by Lattice HyperFrames adapter. Editing generated host files has no effect: every render regenerates them from the canonical VideoPlan and Slide Web Bundle.";

function headerComment(planHash, bundleHash) {
  return [
    `<!-- ${DO_NOT_EDIT} -->`,
    `<!-- plan-hash: ${planHash} -->`,
    `<!-- bundle-hash: ${bundleHash} -->`,
  ].join("\n");
}

/**
 * Extract the stylesheet surface of a Slide Web Bundle index.html in document
 * order — the same engine-neutral extraction the Remotion host uses. External
 * <link rel="stylesheet"> references stay as relative bundle hrefs and inline
 * <style> blocks are carried verbatim so the exporter-guaranteed cascade
 * order (renderer CSS first, theme CSS after) is preserved in the generated
 * composition head.
 */
export function extractBundleStylesheets(indexHtml) {
  const stylesheets = [];
  for (const match of indexHtml.matchAll(/<link\b[^>]*>|<style\b[^>]*>[\s\S]*?<\/style>/gi)) {
    const tag = match[0];
    if (/^<link/i.test(tag)) {
      if (!/\brel\s*=\s*["']?stylesheet/i.test(tag)) continue;
      const href = tag.match(/\bhref\s*=\s*["']([^"']+)["']/i)?.[1];
      if (href === undefined) continue;
      stylesheets.push({ kind: "link", href });
      continue;
    }
    const css = tag.replace(/^<style\b[^>]*>/i, "").replace(/<\/style>$/i, "");
    stylesheets.push({ kind: "inline", css });
  }
  return stylesheets;
}

function escapeAttributeValue(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll('"', "&quot;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;");
}

/**
 * Inline-script-safe JSON: escape `<` so canonical slide markup can never
 * terminate the host configuration script early (</script> inside slide
 * content), and U+2028/2029 so the document stays valid JavaScript.
 */
function serializeInlineScriptJson(value) {
  return JSON.stringify(value)
    .replaceAll("<", "\\u003c")
    .replaceAll("\u2028", "\\u2028")
    .replaceAll("\u2029", "\\u2029");
}

/**
 * Resolve the vendored GSAP runtime shipped in the adapter's own dependency
 * tree. The generated composition registers a real GSAP timeline, so the
 * animation driver must be present without any network fetch (no CDN): the
 * exact pinned gsap package is inlined into the composition at generation
 * time.
 */
export async function resolveVendoredGsapSource() {
  const resolved = import.meta.resolve("gsap/dist/gsap.min.js");
  const source = await fs.readFile(fileURLToPath(resolved), "utf8");
  if (source.includes("</script")) {
    throw new Error("the vendored gsap runtime cannot be inlined into the composition (contains </script>)");
  }
  return source;
}

function stylesheetTag(entry) {
  if (entry.kind === "link") {
    return `<link rel="stylesheet" crossorigin href="${escapeAttributeValue(entry.href)}">`;
  }
  return `<style>${entry.css}</style>`;
}

function serializeHostManifest(hostManifest) {
  return `${JSON.stringify(hostManifest, null, 2)}\n`;
}

/**
 * Deterministically generate the HyperFrames master composition for one
 * prepared plan + Slide Web Bundle pair into `<workDir>/composition`. The
 * composition renders the bundle's own slide markup at the plan's integer
 * frames: a GSAP timeline (the HyperFrames-native time surface, seeked by
 * both the render pipeline and snapshot captures) maps timeline time to the
 * canonical integer frame and applies the active clip's slide HTML plus the
 * frame-state CSS variables on the canvas element.
 *
 * Engine alignment facts encoded here (validated against the Remotion host in
 * the M5 parity suite):
 * - the slide markup is rendered inline in the composition document, not in
 *   a subframe;
 * - `<base href="./bundle/">` resolves the bundle's own relative references
 *   exactly like the Remotion frame document;
 * - local-only @font-face stubs for the declared system families keep the
 *   HyperFrames compiler from injecting substitute webfonts (e.g. mapping
 *   Arial to Inter); if the local family is absent the browser falls through
 *   the stack exactly like the Remotion host does;
 * - `text-rendering: auto` overrides the compiler's injected
 *   `geometricPrecision` rule so glyph advances match the Remotion host;
 * - gsap.min.js is inlined so no network fetch can enter the render.
 *
 * The generation is pure: same (plan, bundle) inputs produce byte-identical
 * composition files, so regeneration before every render is safe and
 * idempotent.
 */
export async function generateHyperFramesHost({ workDir, plan, planHash, bundlePath, bundleHash, manifest: bundleManifest, gsapSource }) {
  const compositionDir = path.join(workDir, HOST_COMPOSITION_DIRNAME);
  const publicDir = compositionDir;
  const compositionBundleDir = path.join(compositionDir, HOST_BUNDLE_DIRNAME);

  await fs.rm(compositionDir, { recursive: true, force: true });
  await fs.mkdir(compositionDir, { recursive: true });
  await fs.cp(bundlePath, compositionBundleDir, { recursive: true });

  const indexHtml = await fs.readFile(path.join(bundlePath, "index.html"), "utf8");
  const stylesheets = extractBundleStylesheets(indexHtml);

  const contentEntryRef = bundleManifest?.entry?.content;
  if (typeof contentEntryRef !== "string" || contentEntryRef === "") {
    throw new Error(`bundle manifest.entry.content is missing; cannot bind plan slides to bundle content`);
  }
  let contentJson;
  try {
    contentJson = JSON.parse(await fs.readFile(path.join(bundlePath, contentEntryRef), "utf8"));
  } catch (error) {
    throw new Error(`cannot read bundle content at ${path.join(bundlePath, contentEntryRef)}: ${error.message}`);
  }
  const contentSlides = Array.isArray(contentJson?.slides) ? contentJson.slides : [];

  // Slide binding rule (engine-neutral): the VideoPlan carries clip identity
  // by slideId, the bundle carries markup by position. Clip at route position
  // k binds to content.slides[k]; when the bundle has fewer slides the clip
  // stays unbound (contentIndex null) and rendering fails fast instead of
  // silently rendering the wrong slide.
  const clips = plan.clips.map((clip, index) => ({
    slideId: clip.slideId,
    startFrame: clip.startFrame,
    durationFrames: clip.durationFrames,
    contentIndex: index < contentSlides.length ? index : null,
    html: index < contentSlides.length && typeof contentSlides[index]?.html === "string"
      ? contentSlides[index].html
      : null,
  }));

  const hostManifest = {
    doNotEdit: `${DO_NOT_EDIT} Source plan hash: ${planHash}`,
    schema: HYPERFRAMES_HOST_SCHEMA,
    compositionId: HYPERFRAMES_COMPOSITION_ID,
    planHash,
    bundleHash,
    deckId: plan.deckId,
    routeId: plan.routeId,
    width: plan.width,
    height: plan.height,
    fps: plan.fps,
    totalFrames: plan.totalFrames,
    slideBinding: "route-position",
    clips: clips.map(({ html, ...rest }) => rest),
    stylesheets,
  };

  const manifestPath = path.join(publicDir, HOST_PUBLIC_MANIFEST_NAME);
  await fs.writeFile(manifestPath, serializeHostManifest(hostManifest), "utf8");

  const compositionSource = buildCompositionDocument({
    plan,
    planHash,
    bundleHash,
    clips,
    stylesheets,
    gsapSource,
  });
  const entryPath = path.join(compositionDir, HOST_ENTRY_NAME);
  await fs.writeFile(entryPath, compositionSource, "utf8");

  return {
    compositionDir,
    entryPoint: entryPath,
    publicDir,
    manifestPath,
    hostManifest,
  };
}

/**
 * The composition document is a fixed, deterministic template: only the
 * provenance header, the bundle stylesheet surface, and the serialized host
 * configuration vary with the (plan, bundle) inputs. The driver registers one
 * paused GSAP timeline spanning the full plan duration; the HyperFrames
 * runtime and producer seek it, and its onUpdate resolves the active plan
 * clip for the canonical integer frame and applies the frame state.
 */
function buildCompositionDocument({ plan, planHash, bundleHash, clips, stylesheets, gsapSource }) {
  const width = plan.width;
  const height = plan.height;
  const fps = plan.fps;
  const totalFrames = plan.totalFrames;
  const durationSeconds = totalFrames / fps;
  const hostConfig = {
    compositionId: HYPERFRAMES_COMPOSITION_ID,
    width,
    height,
    fps,
    totalFrames,
    durationSeconds,
    planHash,
    bundleHash,
    deckId: plan.deckId,
    routeId: plan.routeId,
    clips,
    stylesheets,
  };

  const fontStackFamilies = collectRequestedFontStackFamilies(clips, stylesheets);
  const fontFaceStubs = fontStackFamilies
    .map((family) => `@font-face{font-family:${JSON.stringify(family)};src:local(${JSON.stringify(family)})}`)
    .join("");

  const firstClip = clips[0];
  const firstHtml = firstClip && firstClip.html !== null ? firstClip.html : "";

  return [
    "<!doctype html>",
    "<html>",
    "<head>",
    '<meta charset="utf-8">',
    headerComment(planHash, bundleHash),
    // Local-only font-face stubs: the HyperFrames deterministic-font compiler
    // skips families that already declare @font-face, so no substitute webfont
    // (its Arial→Inter mapping) can enter the render. local() resolves through
    // the same fontconfig substitution the Remotion host's CSS stack uses;
    // when absent, the face fails and the stack falls through identically.
    fontFaceStubs ? `<style>${fontFaceStubs}</style>` : null,
    // The compiler injects `html,body,*{text-rendering:geometricPrecision}`;
    // restoring Chrome's default keeps glyph advances identical to the
    // Remotion host, which carries no text-rendering rule.
    "<style>html,body,*{text-rendering:auto}</style>",
    `<base href="./${HOST_BUNDLE_DIRNAME}/">`,
    stylesheets.map(stylesheetTag).join("\n"),
    "<style>html,body{margin:0;padding:0;background:#ffffff;overflow:hidden}</style>",
    `<script>${gsapSource}</script>`,
    "</head>",
    "<body>",
    `<div id="${HYPERFRAMES_COMPOSITION_ID}" data-composition-id="${HYPERFRAMES_COMPOSITION_ID}"` +
      ` data-width="${width}" data-height="${height}" data-fps="${fps}"` +
      ` data-duration="${formatDurationSeconds(durationSeconds)}">`,
    `<div class="lattice-video-canvas" id="lattice-canvas" data-lattice-slide-id="${escapeAttributeValue(firstClip?.slideId ?? "")}"` +
      ` data-lattice-frame="0"` +
      ` style="--lattice-local-frame:0;--lattice-duration-frames:${firstClip?.durationFrames ?? 0};` +
      `width:${width}px;height:${height}px;position:relative;overflow:hidden;background:#ffffff">${firstHtml}</div>`,
    "</div>",
    `<script>window.LATTICE_HOST = ${serializeInlineScriptJson(hostConfig)};</script>`,
    `<script>${compositionDriverSource()}</script>`,
    "</body>",
    "</html>",
    "",
  ].filter((line) => line !== null).join("\n");
}

/**
 * data-duration must carry the exact plan duration in seconds; the integer
 * plan frame count divided by the integer fps is emitted with full precision
 * so the producer's declared-duration fallback can never round away a frame.
 */
function formatDurationSeconds(durationSeconds) {
  return String(durationSeconds);
}

/**
 * Families requested by the canonical slide surface (inline clip styles plus
 * the bundle stylesheet surface). Only non-generic names get a stub: generic
 * families (sans-serif…) are never fetched by the compiler and must keep
 * falling through to fontconfig.
 */
function collectRequestedFontStackFamilies(clips, stylesheets) {
  const families = [];
  const seen = new Set();
  const consider = (value) => {
    for (const raw of String(value ?? "").split(/,(?![^(]*\))/)) {
      const family = raw.trim().replace(/^["']|["']$/g, "");
      const normalized = family.toLowerCase();
      if (!family) continue;
      if (/^(serif|sans-serif|monospace|cursive|fantasy|system-ui|ui-serif|ui-sans-serif|ui-monospace|ui-rounded|emoji|math|fangsong)$/i.test(normalized)) continue;
      if (normalized.startsWith("var(") || normalized === "inherit" || normalized === "initial" || normalized === "unset") continue;
      const key = normalized;
      if (seen.has(key)) continue;
      seen.add(key);
      families.push(family);
    }
  };
  for (const clip of clips) {
    for (const match of String(clip.html ?? "").matchAll(/font-family\s*:\s*([^;}"']+)/gi)) {
      consider(match[1]);
    }
  }
  for (const entry of stylesheets) {
    if (entry.kind !== "inline") continue;
    for (const match of entry.css.matchAll(/font-family\s*:\s*([^;}]+)/gi)) {
      consider(match[1]);
    }
  }
  return families;
}

function compositionDriverSource() {
  return String.raw`(function () {
  "use strict";
  var cfg = window.LATTICE_HOST;
  var canvas = document.getElementById("lattice-canvas");
  var currentSlideId = canvas.getAttribute("data-lattice-slide-id");
  var appliedKey = null;

  // Plan clips are contiguous by compile contract; a miss is a hard error,
  // never a fallback to a neighbouring clip.
  function resolveClipAtFrame(frame) {
    for (var i = 0; i < cfg.clips.length; i++) {
      var clip = cfg.clips[i];
      if (frame >= clip.startFrame && frame < clip.startFrame + clip.durationFrames) return clip;
    }
    throw new Error("lattice host: frame " + frame + " is outside every plan clip (totalFrames " + cfg.totalFrames + ")");
  }

  function applyFrame(timeline) {
    var frame = Math.round(timeline.time() * cfg.fps);
    var clip = resolveClipAtFrame(frame);
    var localFrame = frame - clip.startFrame;
    var key = clip.slideId + ":" + localFrame;
    if (key === appliedKey) return;
    appliedKey = key;
    if (clip.slideId !== currentSlideId) {
      if (typeof clip.html !== "string") {
        throw new Error('lattice host: clip slide "' + clip.slideId + '" has no bound bundle content (route position has no matching content.json slide)');
      }
      canvas.innerHTML = clip.html;
      canvas.setAttribute("data-lattice-slide-id", clip.slideId);
      currentSlideId = clip.slideId;
    }
    canvas.setAttribute("data-lattice-frame", String(localFrame));
    canvas.style.setProperty("--lattice-local-frame", String(localFrame));
    canvas.style.setProperty("--lattice-duration-frames", String(clip.durationFrames));
  }

  var timeline = window.gsap.timeline({ paused: true });
  timeline.to({ t: 0 }, {
    t: 1,
    duration: cfg.durationSeconds,
    ease: "none",
    onUpdate: function () { applyFrame(timeline); },
  });
  window.__timelines = window.__timelines || {};
  window.__timelines[cfg.compositionId] = timeline;
})();`;
}
