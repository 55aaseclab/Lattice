import { promises as fs } from "node:fs";
import path from "node:path";

export const REMOTION_HOST_SCHEMA = "lattice.remotion-host.v1";
export const REMOTION_COMPOSITION_ID = "lattice-video-plan";
export const HOST_PUBLIC_MANIFEST_NAME = "lattice-host-manifest.json";
export const HOST_CONFIG_NAME = "host-config.js";
export const HOST_ENTRY_NAME = "index.js";
export const HOST_ROOT_NAME = "Root.jsx";
export const HOST_COMPOSITION_NAME = "LatticeComposition.jsx";

const DO_NOT_EDIT = "DO NOT EDIT — generated by Lattice Remotion adapter. Editing generated host files has no effect: every render regenerates them from the canonical VideoPlan and Slide Web Bundle.";

function headerComment(planHash, bundleHash) {
  return [
    `// ${DO_NOT_EDIT}`,
    `// plan-hash: ${planHash}`,
    `// bundle-hash: ${bundleHash}`,
  ].join("\n");
}

/**
 * Extract the stylesheet surface of a Slide Web Bundle index.html in document
 * order: external <link rel="stylesheet"> references stay as relative bundle
 * hrefs (resolved through the copied bundle at render time) and inline
 * <style> blocks are carried verbatim. The exporter guarantees the cascade
 * order (renderer CSS first, theme CSS after), so order must be preserved.
 */
export function extractBundleStylesheets(indexHtml) {
  const stylesheets = [];
  // Single sequential pass over <link> and <style> tags so the extracted
  // surface preserves exact document order (the exporter guarantees the
  // cascade order: renderer CSS first, theme CSS after).
  for (const match of indexHtml.matchAll(/<link\b[^>]*>|<style\b[^>]*>[\s\S]*?<\/style>/gi)) {
    const tag = match[0];
    if (/^<link/i.test(tag)) {
      if (!/\brel\s*=\s*["']?stylesheet/i.test(tag)) continue;
      const href = tag.match(/\bhref\s*=\s*["']([^"']+)["']/i)?.[1];
      if (href === undefined) continue;
      stylesheets.push({ kind: "link", href });
      continue;
    }
    const css = tag.replace(/^<style\b[^>]*>/i, "").replace(/<\/style>$/i, "");
    stylesheets.push({ kind: "inline", css });
  }
  return stylesheets;
}

async function readJsonFile(filePath, label) {
  let raw;
  try {
    raw = await fs.readFile(filePath, "utf8");
  } catch (error) {
    throw new Error(`cannot read ${label} at ${filePath}: ${error.message}`);
  }
  try {
    return JSON.parse(raw);
  } catch (error) {
    throw new Error(`${label} at ${filePath} is not valid JSON: ${error.message}`);
  }
}

function serializeHostManifest(hostManifest) {
  return `${JSON.stringify(hostManifest, null, 2)}\n`;
}

/**
 * Deterministically generate the Remotion host project for one prepared plan +
 * Slide Web Bundle pair into `<workDir>/host`. The host is the only Remotion
 * entry surface: it renders the bundle's own slide markup with the plan's
 * integer frames, and never re-creates slide content in engine-specific form.
 *
 * The generation is pure: same (plan, bundle) inputs produce byte-identical
 * host files, so regeneration before every render is safe and idempotent.
 */
export async function generateRemotionHost({ workDir, plan, planHash, bundlePath, bundleHash, manifest: bundleManifest }) {
  const hostDir = path.join(workDir, "host");
  const publicDir = path.join(hostDir, "public");
  const publicBundleDir = path.join(publicDir, "bundle");

  await fs.rm(hostDir, { recursive: true, force: true });
  await fs.mkdir(publicDir, { recursive: true });
  await fs.cp(bundlePath, publicBundleDir, { recursive: true });

  const indexHtml = await fs.readFile(path.join(bundlePath, "index.html"), "utf8");
  const stylesheets = extractBundleStylesheets(indexHtml);

  const contentEntryRef = bundleManifest?.entry?.content;
  if (typeof contentEntryRef !== "string" || contentEntryRef === "") {
    throw new Error(`bundle manifest.entry.content is missing; cannot bind plan slides to bundle content`);
  }
  const contentJson = await readJsonFile(path.join(bundlePath, contentEntryRef), "bundle content");
  const contentSlides = Array.isArray(contentJson?.slides) ? contentJson.slides : [];

  // Slide binding rule (engine-neutral): the VideoPlan carries clip identity
  // by slideId, the bundle carries markup by position. Clip at route position
  // k binds to content.slides[k]; when the bundle has fewer slides the clip
  // stays unbound (contentIndex null) and rendering fails fast instead of
  // silently rendering the wrong slide.
  const clips = plan.clips.map((clip, index) => ({
    slideId: clip.slideId,
    startFrame: clip.startFrame,
    durationFrames: clip.durationFrames,
    contentIndex: index < contentSlides.length ? index : null,
  }));

  const hostManifest = {
    doNotEdit: `${DO_NOT_EDIT} Source plan hash: ${planHash}`,
    schema: REMOTION_HOST_SCHEMA,
    compositionId: REMOTION_COMPOSITION_ID,
    planHash,
    bundleHash,
    deckId: plan.deckId,
    routeId: plan.routeId,
    width: plan.width,
    height: plan.height,
    fps: plan.fps,
    totalFrames: plan.totalFrames,
    slideBinding: "route-position",
    clips,
    stylesheets,
  };

  const manifestPath = path.join(publicDir, HOST_PUBLIC_MANIFEST_NAME);
  await fs.writeFile(manifestPath, serializeHostManifest(hostManifest), "utf8");

  const configPath = path.join(hostDir, HOST_CONFIG_NAME);
  await fs.writeFile(
    configPath,
    [
      headerComment(planHash, bundleHash),
      "",
      "export const LATTICE_HOST_CONFIG = {",
      `  compositionId: ${JSON.stringify(REMOTION_COMPOSITION_ID)},`,
      `  width: ${JSON.stringify(plan.width)},`,
      `  height: ${JSON.stringify(plan.height)},`,
      `  fps: ${JSON.stringify(plan.fps)},`,
      `  durationInFrames: ${JSON.stringify(plan.totalFrames)},`,
      `  planHash: ${JSON.stringify(planHash)},`,
      `  bundleHash: ${JSON.stringify(bundleHash)},`,
      `  deckId: ${JSON.stringify(plan.deckId)},`,
      `  routeId: ${JSON.stringify(plan.routeId)},`,
      `};`,
      "",
    ].join("\n"),
    "utf8",
  );

  const entryPath = path.join(hostDir, HOST_ENTRY_NAME);
  await fs.writeFile(
    entryPath,
    [
      headerComment(planHash, bundleHash),
      "",
      'import { registerRoot } from "remotion";',
      'import { RemotionRoot } from "./Root.jsx";',
      "",
      "registerRoot(RemotionRoot);",
      "",
    ].join("\n"),
    "utf8",
  );

  const rootPath = path.join(hostDir, HOST_ROOT_NAME);
  await fs.writeFile(
    rootPath,
    [
      headerComment(planHash, bundleHash),
      "",
      'import React from "react";',
      'import { Composition } from "remotion";',
      'import { LatticeComposition } from "./LatticeComposition.jsx";',
      'import { LATTICE_HOST_CONFIG } from "./host-config.js";',
      "",
      "export const RemotionRoot = () => {",
      "  return (",
      "    <Composition",
      "      id={LATTICE_HOST_CONFIG.compositionId}",
      "      component={LatticeComposition}",
      "      durationInFrames={LATTICE_HOST_CONFIG.durationInFrames}",
      "      fps={LATTICE_HOST_CONFIG.fps}",
      "      width={LATTICE_HOST_CONFIG.width}",
      "      height={LATTICE_HOST_CONFIG.height}",
      "      defaultProps={{}}",
      "    />",
      "  );",
      "};",
      "",
    ].join("\n"),
    "utf8",
  );

  const compositionPath = path.join(hostDir, HOST_COMPOSITION_NAME);
  await fs.writeFile(compositionPath, compositionSource(planHash, bundleHash), "utf8");

  return {
    hostDir,
    entryPoint: entryPath,
    publicDir,
    manifestPath,
    configPath,
    hostManifest,
  };
}

// The composition source is a fixed, deterministic string (only the provenance
// header varies with the plan). It renders, for every integer frame:
//   1. the active plan clip resolved from useCurrentFrame() (no backend time),
//   2. the bundle's own slide markup in a sandboxed document that loads the
//      bundle's stylesheet surface and slide assets through <base href>,
//   3. a paint acknowledgment posted by the frame document after fonts and
//      images settle — Remotion waits for it via delayRender before capture.
function compositionSource(planHash, bundleHash) {
  return [
    headerComment(planHash, bundleHash),
    "",
    'import React, { useEffect, useMemo, useRef, useState } from "react";',
    'import { AbsoluteFill, continueRender, delayRender, staticFile, useCurrentFrame } from "remotion";',
    'import { LATTICE_HOST_CONFIG } from "./host-config.js";',
    "",
    "const PAINT_MESSAGE_TYPE = \"lattice-frame-painted\";",
    "",
    "function escapeAttributeValue(value) {",
    "  return String(value)",
    '    .replaceAll("&", "&amp;")',
    '    .replaceAll("\\"", "&quot;")',
    '    .replaceAll("<", "&lt;")',
    '    .replaceAll(">", "&gt;");',
    "}",
    "",
    "// Plan clips are contiguous by compile contract; a miss is a hard error,",
    "// never a fallback to a neighbouring clip.",
    "function resolveClipAtFrame(clips, frame) {",
    "  for (const clip of clips) {",
    "    if (frame >= clip.startFrame && frame < clip.startFrame + clip.durationFrames) {",
    "      return clip;",
    "    }",
    "  }",
    "  throw new Error(",
    '    "lattice host: frame " + frame + " is outside every plan clip (totalFrames " +',
    "      LATTICE_HOST_CONFIG.durationInFrames + \")\"",
    "  );",
    "}",
    "",
    "function resolveBoundSlideHtml(bundleContent, clip) {",
    "  if (clip.contentIndex === null || clip.contentIndex === undefined) {",
    "    throw new Error(",
    '      "lattice host: clip slide \\"" + clip.slideId + "\\" cannot be bound to bundle content " +',
    '      "(route position has no matching content.json slide)"',
    "    );",
    "  }",
    "  const slide = bundleContent.slides[clip.contentIndex];",
    "  if (!slide || typeof slide.html !== \"string\") {",
    "    throw new Error(",
    '      "lattice host: bundle content slide at index " + clip.contentIndex + " has no html for clip \\"" +',
    "      clip.slideId + \"\\\"\"",
    "    );",
    "  }",
    "  return slide.html;",
    "}",
    "",
    "function stylesheetTags(stylesheets) {",
    "  const tags = [];",
    "  for (const entry of stylesheets) {",
    "    if (entry.kind === \"link\") {",
    "      tags.push('<link rel=\"stylesheet\" href=\"' + escapeAttributeValue(entry.href) + '\">');",
    "    } else if (entry.kind === \"inline\") {",
    "      tags.push(\"<style>\" + entry.css + \"</style>\");",
    "    }",
    "  }",
    "  return tags.join(\"\\n\");",
    "}",
    "",
    "function buildFrameDocument({ hostManifest, bundleContent, bundleBaseHref, clip, frame, localFrame }) {",
    "  const width = LATTICE_HOST_CONFIG.width;",
    "  const height = LATTICE_HOST_CONFIG.height;",
    "  const slideHtml = resolveBoundSlideHtml(bundleContent, clip);",
    "  const variables = [",
    '    "--lattice-local-frame:" + localFrame,',
    '    "--lattice-duration-frames:" + clip.durationFrames,',
    "  ].join(\";\");",
    "  const canvasAttributes = [",
    '    "class=\\"lattice-video-canvas\\"",',
    '    "data-lattice-slide-id=\\"" + escapeAttributeValue(clip.slideId) + "\\"",',
    '    "data-lattice-frame=\\"" + localFrame + "\\"",',
    '    "style=\\"" + escapeAttributeValue(variables) + ";width:" + width + "px;height:" + height + "px;position:relative;overflow:hidden;background:#ffffff\\"",',
    "  ].join(\" \");",
    "  return [",
    "    \"<!doctype html><html><head><meta charset=\\\"utf-8\\\">\",",
    '    "<base href=\\"" + escapeAttributeValue(bundleBaseHref) + "\\">",',
    "    stylesheetTags(hostManifest.stylesheets),",
    "    \"<style>html,body{margin:0;padding:0;background:#ffffff;overflow:hidden}\",",
    "    \"body{width:\" + width + \"px;height:\" + height + \"px}</style>\",",
    "    \"</head><body>\",",
    "    \"<div \" + canvasAttributes + \">\" + slideHtml + \"</div>\",",
    "    paintScript(frame),",
    "    \"</body></html>\",",
    "  ].join(\"\\n\");",
    "}",
    "",
    "// The frame document acknowledges paint only after its fonts and images",
    "// verifiably settled (or verifiably failed) and two animation frames",
    "// flushed — the same readiness contract as the Slide Runtime barrier.",
    "function paintScript(frame) {",
    "  return [",
    "    \"<script>\",",
    "    \"(function () {\",",
    "    \"  var FRAME = \" + JSON.stringify(frame) + \";\",",
    "    \"  function post() {\",",
    "    \"    try {\",",
    "    \"      parent.postMessage({ type: \\\"\" + PAINT_MESSAGE_TYPE + \"\\\", frame: FRAME }, \\\"*\\\");\",",
    "    \"    } catch (error) {}\",",
    "    \"  }\",",
    "    \"  function flush() {\",",
    "    \"    requestAnimationFrame(function () {\",",
    "    \"      requestAnimationFrame(post);\",",
    "    \"    });\",",
    "    \"  }\",",
    "    \"  function waitImages() {\",",
    "    \"    var images = Array.prototype.slice.call(document.images || []);\",",
    "    \"    Promise.all(images.map(function (image) {\",",
    "    \"      if (image.complete) return Promise.resolve();\",",
    "    \"      return new Promise(function (resolve) {\",",
    "    \"        image.addEventListener(\\\"load\\\", resolve, { once: true });\",",
    "    \"        image.addEventListener(\\\"error\\\", resolve, { once: true });\",",
    "    \"      });\",",
    "    \"    })).then(flush, flush);\",",
    "    \"  }\",",
    "    \"  function settle() {\",",
    "    \"    if (document.fonts && document.fonts.ready) {\",",
    "    \"      var bound = new Promise(function (resolve) { setTimeout(resolve, 10000); });\",",
    "    \"      Promise.race([document.fonts.ready, bound]).catch(function () {}).then(waitImages, waitImages);\",",
    "    \"    } else {\",",
    "    \"      waitImages();\",",
    "    \"    }\",",
    "    \"  }\",",
    "    \"  if (document.readyState === \\\"complete\\\") { settle(); } else {\",",
    "    \"    window.addEventListener(\\\"load\\\", settle, { once: true });\",",
    "    \"  }\",",
    "    \"})();\",",
    "    \"</\" + \"script>\",",
    "  ].join(\"\\n\");",
    "}",
    "",
    "export const LatticeComposition = () => {",
    "  const frame = useCurrentFrame();",
    "  const [loaded, setLoaded] = useState(null);",
    "  const [loadError, setLoadError] = useState(null);",
    "  const iframeRef = useRef(null);",
    "",
    "  useEffect(() => {",
    "    let cancelled = false;",
    "    const handle = delayRender(\"lattice host data load\");",
    "    Promise.all([",
    "      fetch(staticFile(" + JSON.stringify(HOST_PUBLIC_MANIFEST_NAME) + ")).then((response) => {",
    "        if (!response.ok) throw new Error(\"host manifest fetch failed: \" + response.status);",
    "        return response.json();",
    "      }),",
    "      fetch(staticFile(\"bundle/content.json\")).then((response) => {",
    "        if (!response.ok) throw new Error(\"bundle content fetch failed: \" + response.status);",
    "        return response.json();",
    "      }),",
    "    ])",
    "      .then(([hostManifest, bundleContent]) => {",
    "        if (cancelled) {",
    "          continueRender(handle);",
    "          return;",
    "        }",
    "        setLoaded({ hostManifest, bundleContent });",
    "        continueRender(handle);",
    "      })",
    "      .catch((error) => {",
    "        if (cancelled) {",
    "          continueRender(handle);",
    "          return;",
    "        }",
    "        setLoadError(String((error && error.stack) || error));",
    "        continueRender(handle);",
    "      });",
    "    return () => {",
    "      cancelled = true;",
    "    };",
    "  }, []);",
    "",
    "  if (loadError) {",
    "    throw new Error(\"lattice host data load failed: \" + loadError);",
    "  }",
    "",
    "  // The frame document and its paint acknowledgment are derived without",
    "  // conditional hooks: every render calls the same hook sequence.",
    "  const bundleBaseHref = useMemo(() => {",
    "    const base = staticFile(\"bundle/\");",
    "    return base.endsWith(\"/\") ? base : base + \"/\";",
    "  }, []);",
    "  const frameState = loaded === null ? null : (() => {",
    "    const { hostManifest, bundleContent } = loaded;",
    "    const clip = resolveClipAtFrame(hostManifest.clips, frame);",
    "    return {",
    "      clip,",
    "      localFrame: frame - clip.startFrame,",
    "      srcDoc: buildFrameDocument({",
    "        hostManifest,",
    "        bundleContent,",
    "        bundleBaseHref,",
    "        clip,",
    "        frame,",
    "        localFrame: frame - clip.startFrame,",
    "      }),",
    "    };",
    "  })();",
    "",
    "  useEffect(() => {",
    "    if (!frameState) return undefined;",
    "    let settled = false;",
    "    const handle = delayRender(\"lattice frame paint \" + frame);",
    "    function onMessage(event) {",
    "      const data = event.data;",
    "      if (!data || data.type !== PAINT_MESSAGE_TYPE || data.frame !== frame) return;",
    "      settled = true;",
    "      continueRender(handle);",
    "    }",
    "    window.addEventListener(\"message\", onMessage);",
    "    return () => {",
    "      window.removeEventListener(\"message\", onMessage);",
    "      if (!settled) {",
    "        continueRender(handle);",
    "      }",
    "    };",
    "  }, [frame, frameState && frameState.srcDoc]);",
    "",
    "  return (",
    '    <AbsoluteFill style={{ backgroundColor: "#ffffff" }}>',
    "      {frameState === null ? null : (",
    "        <iframe",
    "          ref={iframeRef}",
    "          title=\"lattice slide frame\"",
    "          srcDoc={frameState.srcDoc}",
    "          width={LATTICE_HOST_CONFIG.width}",
    "          height={LATTICE_HOST_CONFIG.height}",
    '          style={{ border: "none", display: "block", width: LATTICE_HOST_CONFIG.width, height: LATTICE_HOST_CONFIG.height }}',
    "        />",
    "      )}",
    "    </AbsoluteFill>",
    "  );",
    "};",
    "",
  ].join("\n");
}
